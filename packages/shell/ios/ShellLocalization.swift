  static func usesSimplifiedChinese(_ languages: [String]) -> Bool {
    guard let preferred = languages.first else { return false }
    let parts = preferred.lowercased().replacingOccurrences(of: "_", with: "-").split(separator: "-")
    guard parts.first == "zh" else { return false }
    let qualifiers = parts.dropFirst().prefix(while: { $0.count > 1 })
    if qualifiers.contains(where: { ["hant", "tw", "hk", "mo"].contains($0) }) { return false }
    return parts.count == 1 || qualifiers.contains(where: { ["hans", "cn", "sg"].contains($0) })
  }

  static func t(_ text: String) -> String {
    guard usesSimplifiedChinese(preferredLanguagesOverride ?? Locale.preferredLanguages) else { return text }
    return simplifiedChinese[text] ?? text
  }

  static func t(_ text: String, replacing token: String, with value: String) -> String {
    t(text).replacingOccurrences(of: "{\(token)}", with: value)
  }

