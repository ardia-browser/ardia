fn is_small_order(encoding: &[u8]) -> bool {
    SMALL_ORDER_Y
        .iter()
        .any(|y| y[..31] == encoding[..31] && y[31] == encoding[31] & 0x7f)
}

pub(crate) fn has_small_order_key_or_r(public_key: &[u8; 32], signature: &[u8; 64]) -> bool {
    is_small_order(public_key) || is_small_order(&signature[..32])
}

#[cfg(test)]
mod tests {
    use super::*;
    use ed25519_dalek::VerifyingKey;

    #[test]
    fn every_listed_encoding_that_decodes_is_a_small_order_point() {
        let mut decoded = 0;
        for y in SMALL_ORDER_Y {
            for sign in [0u8, 0x80] {
                let mut encoding = y;
                encoding[31] |= sign;
                assert!(is_small_order(&encoding));
                if let Ok(key) = VerifyingKey::from_bytes(&encoding) {
                    assert!(key.is_weak(), "{encoding:02x?}");
                    decoded += 1;
                }
            }
        }
        assert!(decoded >= 8);
    }

    #[test]
    fn ordinary_keys_are_not_small_order() {
        let rfc_8032_test_1 = [
            0xd7, 0x5a, 0x98, 0x01, 0x82, 0xb1, 0x0a, 0xb7, 0xd5, 0x4b, 0xfe, 0xd3, 0xc9, 0x64, 0x07, 0x3a, 0x0e, 0xe1,
            0x72, 0xf3, 0xda, 0xa6, 0x23, 0x25, 0xaf, 0x02, 0x1a, 0x68, 0xf7, 0x07, 0x51, 0x1a,
        ];
        assert!(!is_small_order(&rfc_8032_test_1));
        assert!(!VerifyingKey::from_bytes(&rfc_8032_test_1).unwrap().is_weak());
        let mut near = [0u8; 32];
        near[0] = 2;
        assert!(!is_small_order(&near));
    }

    #[test]
    fn the_key_and_r_are_checked_independently() {
        let mut key = [0u8; 32];
        key[0] = 2;
        let mut signature = [0u8; 64];
        signature[0] = 2;
        assert!(!has_small_order_key_or_r(&key, &signature));
        signature[0] = 1;
        assert!(has_small_order_key_or_r(&key, &signature));
        signature[0] = 2;
        key[0] = 1;
        assert!(has_small_order_key_or_r(&key, &signature));
    }
}
