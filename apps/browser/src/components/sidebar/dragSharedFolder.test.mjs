import assert from "node:assert/strict";
import { test } from "node:test";
const { shellNativeModules } = await import("../../test-native/shell.ts");
globalThis.acTestNativeModules = { ArdiaSharedFolders: { location: () => ({ path: "/scratch", iCloudAvailable: true, iCloudPath: "/scratch" }) } };
await import("../../test-native/index.ts");
const D = await import("./fixtures/dragScene.mjs");
const { world, regionsOf } = await import("./fixtures/dragWorld.mjs");
const { pinKeyOf } = await import("../../state/browser/model.ts");
const { createFolder, live, useLive } = await import("../../state/live/store.ts");
const { guardGroupClose, keepGroupsOpen } = await import("../../state/groups/closeGuard.ts");
const { bindFolder } = await import("../../state/sharedFolders/store.ts");
const { confirmRemovingShared, sharedFolderOfGroup } = await import("../../state/sharedFolders/removal.ts");
const { devTabPresses } = await import("../../state/telemetry/tabPresses.ts");
const { S, entryKey, mount, sceneLayout, centre } = D;

guardGroupClose(confirmRemovingShared);
keepGroupsOpen((groupId, s = S()) => !!sharedFolderOfGroup(s, groupId));

test("a shared folder's drop that waits for an answer moves nothing: not its live folder, its landing or the drop count", async (t) => {
  const real = shellNativeModules.ArdiaDialogs.confirm;
  let asked = 0;
  shellNativeModules.ArdiaDialogs.confirm = async () => (asked++, { confirmed: false, suppressed: false });
  t.after(() => (shellNativeModules.ArdiaDialogs.confirm = real));
  const W = world("a", "b", "link");
  const team = S().groupTabs([W.id.link], { pinned: true, name: "Team" });
  const { profileId } = S().groups[team];
  const key = pinKeyOf(S().groups[team]);
  bindFolder(profileId, key, "/scratch/Dragged Team");
  const inbox = createFolder(profileId, "pullRequests");
  useLive.setState((l) => ({ folders: { ...l.folders, [inbox]: { ...l.folders[inbox], after: entryKey("group", key) } } }));
  const L = sceneLayout({ top: 150 });
  L.group(team, { section: "pinnedGroups" }, (m) => L.row(W.id.link, m));
  L.live(inbox);
  L.tail("pinnedGroups");
  L.skip(10);
  const listTop = L.y;
  L.row(W.id.a).row(W.id.b).tail("list");
  const { c } = mount({ entries: L.entries, regions: regionsOf(L, { pinnedGroups: [150, listTop], list: [listTop, L.y] }) });
  const landed = [];
  const landingSpot = c.landingSpot.bind(c);
  c.landingSpot = (drop) => (landed.push(drop.type), landingSpot(drop));
  const gaps = devTabPresses().drops_gap;
  const anchor = live().folders[inbox].after;
  const header = L.entries.find((e) => e.key === entryKey("group", team)).header;
  const below = L.entries.find((e) => e.key === entryKey("tab", W.id.b)).frame;
  const { drop } = await D.drag(c, entryKey("group", team), { x: header.x + 20, y: header.y + 10 }, centre(below, -below.h * 0.3));
  assert.equal(drop.type, "group", "setup: the list takes the folder");
  c.end(true);
  await D.settle();
  assert.equal(asked, 1);
  assert.equal(S().groups[team].pinned, true);
  assert.equal(live().folders[inbox].after, anchor, "the live folder below it keeps its place");
  assert.equal(devTabPresses().drops_gap, gaps, "a drop that waits isn't a drop in the gap");
  assert.deepEqual(landed, ["none"], "the ghost lands back home");
});
